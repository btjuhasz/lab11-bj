import math


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def div(a, b):
    return a / b


def logarithm(a, b):
    return math.log(a, b)


def hypotenuse(a, b):
    return math.hypot(a, b)


def square_root(a):
    return math.sqrt(a)

